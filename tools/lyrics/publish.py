"""Publishing rules: provenance hash, edited-file protection, backups, atomic writes."""
from __future__ import annotations

import hashlib
import json
import logging
import shutil
from datetime import datetime
from pathlib import Path
from typing import Any

from . import cache
from .cues import srt_time

log = logging.getLogger("lyrics")

GENERATED_BY = "Demucs + faster-whisper; v2-i18n text and timing pipeline"


def canonical_lines(lines: list[dict[str, Any]]) -> list[dict[str, Any]]:
    result = []
    for line in lines:
        words = []
        for word in line.get("words") or []:
            item = {
                "text": str(word.get("text", "")),
                "start": round(float(word.get("start", 0.0)), 3),
                "end": round(float(word.get("end", 0.0)), 3),
            }
            if word.get("inferred"):
                item["inferred"] = True
            words.append(item)
        result.append({
            "start": round(float(line.get("start", 0.0)), 3),
            "end": round(float(line.get("end", 0.0)), 3),
            "text": " ".join(str(line.get("text", "")).split()),
            "instrumental": bool(line.get("instrumental")),
            "words": words,
        })
    return result


def lines_sha256(lines: list[dict[str, Any]]) -> str:
    encoded = json.dumps(canonical_lines(lines), ensure_ascii=False,
                         sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def build_srt(lines: list[dict[str, Any]]) -> str:
    blocks = []
    for index, line in enumerate(lines, 1):
        text = "[Instrumental]" if line.get("instrumental") else str(
            line.get("text", "")).strip()
        blocks.append(
            f"{index}\n{srt_time(line['start'])} --> {srt_time(line['end'])}\n"
            f"{text}\n")
    return "\n".join(blocks)


def build_payload(stem: str, cues: list[dict[str, Any]], duration: float,
                  pipeline: dict[str, Any]) -> dict[str, Any]:
    lines = canonical_lines(cues)
    payload = {
        "version": 1,
        "song": stem,
        "duration": round(float(duration), 3),
        "generated_by": GENERATED_BY,
        "pipeline": dict(pipeline),
        "lines": lines,
    }
    payload["pipeline"]["output_sha256"] = lines_sha256(lines)
    return payload


def _read_json(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def _srt_matches(words: dict[str, Any], srt_text: str) -> bool:
    expected = build_srt(words.get("lines") or [])

    def normalize(value: str) -> str:
        return value.replace("\r\n", "\n").strip()

    return normalize(expected) == normalize(srt_text)


def inspect_existing(output_dir: Path, stem: str) -> dict[str, Any]:
    srt_path = output_dir / f"{stem}.srt"
    words_path = output_dir / f"{stem}.words.json"
    srt_exists = srt_path.is_file()
    words_exists = words_path.is_file()
    if not srt_exists and not words_exists:
        return {"edited": False, "reason": "new", "srt_path": srt_path,
                "words_path": words_path, "data": None}
    if not srt_exists or not words_exists:
        return {"edited": True, "reason": "incomplete lyric pair",
                "srt_path": srt_path, "words_path": words_path, "data": None}
    data = _read_json(words_path)
    if data is None:
        return {"edited": True, "reason": "unreadable .words.json",
                "srt_path": srt_path, "words_path": words_path, "data": None}
    pipeline = data.get("pipeline")
    stored = pipeline.get("output_sha256") if isinstance(pipeline, dict) else None
    if not isinstance(stored, str) or not stored:
        return {"edited": True, "reason": "no pipeline provenance block",
                "srt_path": srt_path, "words_path": words_path, "data": data}
    computed = lines_sha256(data.get("lines") or [])
    if computed != stored:
        return {"edited": True, "reason": "lyric lines changed since generation",
                "srt_path": srt_path, "words_path": words_path, "data": data}
    try:
        srt_text = srt_path.read_text(encoding="utf-8-sig")
    except OSError:
        return {"edited": True, "reason": "unreadable .srt",
                "srt_path": srt_path, "words_path": words_path, "data": data}
    if not _srt_matches(data, srt_text):
        return {"edited": True, "reason": ".srt does not match .words.json",
                "srt_path": srt_path, "words_path": words_path, "data": data}
    return {"edited": False, "reason": "generated by this pipeline",
            "srt_path": srt_path, "words_path": words_path, "data": data}


def backup_pair(stem: str, srt_path: Path, words_path: Path,
                backup_dir: Path) -> list[str]:
    existing = [path for path in (srt_path, words_path) if path.is_file()]
    if not existing:
        return []
    target = backup_dir / stem
    target.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    saved = []
    for path in existing:
        destination = target / f"{stamp}-{path.name}"
        shutil.copy2(path, destination)
        saved.append(str(destination))
    return saved


def write_outputs(stem: str, cues: list[dict[str, Any]], duration: float,
                  pipeline: dict[str, Any], output_dir: Path,
                  *, overwrite_edited: bool = False,
                  backup_dir: Path | None = None) -> dict[str, Any]:
    output_dir.mkdir(parents=True, exist_ok=True)
    existing = inspect_existing(output_dir, stem)
    if existing["edited"] and not overwrite_edited:
        log.warning("  skipped %s: %s (use --overwrite-edited to replace)",
                    stem, existing["reason"])
        return {
            "written": False,
            "skipped": True,
            "reason": existing["reason"],
            "srt_path": existing["srt_path"],
            "words_path": existing["words_path"],
        }

    backups = []
    if existing["reason"] != "new" and backup_dir is not None:
        backups = backup_pair(stem, existing["srt_path"],
                              existing["words_path"], backup_dir)
        if backups:
            log.info("  backed up previous lyric pair: %d file(s)", len(backups))

    payload = build_payload(stem, cues, duration, pipeline)
    srt_text = build_srt(payload["lines"])
    # Words first: the SRT is the --missing completion marker.
    cache.atomic_write_json(existing["words_path"], payload)
    cache.atomic_write_text(existing["srt_path"], srt_text)

    return {
        "written": True,
        "skipped": False,
        "reason": existing["reason"],
        "srt_path": existing["srt_path"],
        "words_path": existing["words_path"],
        "backups": backups,
        "output_sha256": payload["pipeline"]["output_sha256"],
    }
